"""Full-size canopy pattern as SVG (laser cutting) plus A4 tiles for printing.

Line key: solid black = cut line (includes seam allowance), dashed blue = stitch /
finished edge, red crosses = shroud line attachment points. Units are mm, so
the SVG prints at true size when printed at 100 % ("actual size").
"""

import math
from datetime import date
from pathlib import Path

import numpy as np

from . import parachute as P

A4 = (210.0, 297.0)
MARGIN, OVERLAP, PAD = 10.0, 10.0, 15.0


def offset_polygon(pts: np.ndarray, dist: float) -> np.ndarray:
    """Offset a closed polygon outwards by dist (mitred corners, spikes clamped)."""
    keep = [pts[0]]
    for p in pts[1:]:
        if np.hypot(*(p - keep[-1])) > 1e-9:
            keep.append(p)
    if np.hypot(*(keep[0] - keep[-1])) < 1e-9:
        keep.pop()
    pts = np.array(keep)
    x, y = pts[:, 0], pts[:, 1]
    if 0.5 * np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y) < 0:  # make anticlockwise
        pts = pts[::-1]
    out = []
    n = len(pts)
    for i in range(n):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % n]
        e1 = (p1 - p0) / np.hypot(*(p1 - p0))
        e2 = (p2 - p1) / np.hypot(*(p2 - p1))
        n1, n2 = np.array([e1[1], -e1[0]]), np.array([e2[1], -e2[0]])
        bis = n1 + n2
        if np.hypot(*bis) < 1e-9:
            bis = n1
        bis = bis / np.hypot(*bis)
        m = min(dist / max(np.dot(bis, n1), 1e-9), 4 * dist)
        out.append(p1 + bis * m)
    return np.array(out)


def attachment_points(canopy: P.Canopy, n_lines: int) -> np.ndarray:
    """Where the shroud lines attach, in the same frame as the flat piece (m)."""
    outline = canopy.pieces[0]
    if canopy.shape == "flat_hexagon":
        return outline
    if canopy.shape == "flat_circle":
        r = canopy.width_m / 2
        a = np.linspace(0, 2 * math.pi, n_lines + 1)[:-1]
        return np.column_stack([r * np.cos(a), r * np.sin(a)])
    if canopy.shape == "cruciform":
        h, a = canopy.dims["arm width"] / 2, canopy.width_m / 2
        return np.array([[h, a], [-h, a], [-a, h], [-a, -h], [-h, -a], [h, -a], [a, -h], [a, h]])
    # hemispherical gore: lines at the two skirt corners (shared with neighbouring gores)
    top = outline[np.argmax(outline[:, 1])]
    return np.array([[top[0], top[1]], [-top[0], top[1]]])


def _path(pts_mm, closed=True):
    d = "M " + " L ".join(f"{x:.2f},{y:.2f}" for x, y in pts_mm)
    return d + (" Z" if closed else "")


def build_drawing(canopy: P.Canopy, pc) -> tuple[str, float, float]:
    """Return (svg body, width mm, height mm) of the pattern drawing."""
    seam = pc.seam_allowance_mm
    piece = canopy.pieces[0] * 1000
    cut = offset_polygon(piece, seam)
    att = attachment_points(canopy, P.n_lines_for(pc, canopy)) * 1000

    lo = cut.min(axis=0) - PAD
    hi = cut.max(axis=0) + PAD
    w, h = hi[0] - lo[0], hi[1] - lo[1] + 40          # room for the text block

    def tf(p):  # metres-mm frame → SVG (y down)
        p = np.atleast_2d(p)
        return np.column_stack([p[:, 0] - lo[0], hi[1] - p[:, 1]])

    els = [
        f'<path d="{_path(tf(cut))}" fill="none" stroke="#000" stroke-width="0.4"/>',
        f'<path d="{_path(tf(piece))}" fill="none" stroke="#2a78d6" stroke-width="0.3" stroke-dasharray="3,2"/>',
    ]
    if canopy.hole_d_m > 0 and canopy.shape != "hemispherical":
        cx, cy = tf(np.array([0.0, 0.0]))[0]
        r_fin = canopy.hole_d_m * 500
        els.append(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r_fin:.2f}" fill="none" '
                   f'stroke="#2a78d6" stroke-width="0.3" stroke-dasharray="3,2"/>')
        if r_fin - seam > 0:
            els.append(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r_fin - seam:.2f}" fill="none" '
                       f'stroke="#000" stroke-width="0.4"/>')
    for x, y in tf(att):
        els.append(f'<path d="M {x - 3:.2f},{y:.2f} L {x + 3:.2f},{y:.2f} M {x:.2f},{y - 3:.2f} '
                   f'L {x:.2f},{y + 3:.2f}" stroke="#e34948" stroke-width="0.4"/>')

    # Text block and 100 mm scale bar
    ty = hi[1] - lo[1] + 6
    dims = ", ".join(f"{k} {v * 1000:.0f} mm" for k, v in canopy.dims.items())
    cut_n = f"CUT {canopy.n_pieces} – " if canopy.n_pieces > 1 else ""
    lines = [
        f"{cut_n}{P.SHAPES[canopy.shape].label} canopy – {dims}",
        f"Spill hole {canopy.hole_d_m * 1000:.0f} mm ({canopy.spill_pct:.0f} % of width); "
        f"seam allowance {seam:.0f} mm; {P.n_lines_for(pc, canopy)} lines",
        "Solid = cut, dashed = stitch line, red + = line attachment. Print at 100 % and check the scale bar.",
        f"Generated by cansat_design (written with Claude Code), {date.today().isoformat()}",
    ]
    for i, t in enumerate(lines):
        els.append(f'<text x="5" y="{ty + i * 5:.1f}" font-family="sans-serif" font-size="3.2">{t}</text>')
    sy = ty + len(lines) * 5 + 2
    els.append(f'<path d="M 5,{sy} L 105,{sy} M 5,{sy - 2} L 5,{sy + 2} M 105,{sy - 2} L 105,{sy + 2}" '
               f'stroke="#000" stroke-width="0.4"/>')
    els.append(f'<text x="110" y="{sy + 1}" font-family="sans-serif" font-size="3.2">100 mm</text>')
    w = max(w, 135.0)
    return "\n".join(els), w, h


def _svg(body, w, h, view=None):
    vb = view or (0, 0, w, h)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:.1f}mm" height="{h:.1f}mm" '
            f'viewBox="{vb[0]:.2f} {vb[1]:.2f} {vb[2]:.2f} {vb[3]:.2f}">\n{body}\n</svg>\n')


def export_svg(canopy: P.Canopy, pc, outdir) -> list[Path]:
    """Write canopy_pattern.svg (full size) and canopy_A4_rRcC.svg tiles. Returns paths."""
    outdir = Path(outdir)
    body, w, h = build_drawing(canopy, pc)
    paths = [outdir / "canopy_pattern.svg"]
    paths[0].write_text(_svg(body, w, h))

    pw, ph = A4[0] - 2 * MARGIN, A4[1] - 2 * MARGIN
    nx = max(1, math.ceil((w - OVERLAP) / (pw - OVERLAP)))
    ny = max(1, math.ceil((h - OVERLAP) / (ph - OVERLAP)))
    for old in outdir.glob("canopy_A4_*.svg"):
        old.unlink()
    for r in range(ny):
        for c in range(nx):
            x0, y0 = c * (pw - OVERLAP), r * (ph - OVERLAP)
            page = (f'<defs><clipPath id="c"><rect x="{MARGIN}" y="{MARGIN}" width="{pw}" height="{ph}"/>'
                    f'</clipPath></defs>\n<g clip-path="url(#c)"><g transform="translate('
                    f'{MARGIN - x0:.2f},{MARGIN - y0:.2f})">\n{body}\n</g></g>\n'
                    f'<rect x="{MARGIN}" y="{MARGIN}" width="{pw}" height="{ph}" fill="none" '
                    f'stroke="#999" stroke-width="0.2" stroke-dasharray="1,1"/>\n'
                    f'<text x="{MARGIN}" y="{MARGIN - 3}" font-family="sans-serif" font-size="3">'
                    f'Row {r + 1}, column {c + 1} of {ny} × {nx} – overlap {OVERLAP:.0f} mm with neighbours, '
                    f'tape edges together</text>')
            p = outdir / f"canopy_A4_r{r + 1}c{c + 1}.svg"
            p.write_text(_svg(page, *A4))
            paths.append(p)
    return paths
